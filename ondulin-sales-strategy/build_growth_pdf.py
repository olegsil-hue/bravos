#!/usr/bin/env python3
"""PDF 16:9 — открывается везде, без PowerPoint."""
from fpdf import FPDF

R = (180, 35, 24)
INK = (28, 25, 23)
MUTED = (87, 83, 78)
W, H = 338.67, 190.5  # 16:9 mm (13.333x7.5 in)


class Deck(FPDF):
    def __init__(self):
        super().__init__(orientation="L", unit="mm", format=(W, H))
        self.add_font("DejaVu", "", "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
        self.add_font("DejaVu", "B", "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf")
        self.set_auto_page_break(False)
        self.nslide = 0
        self.total = 12

    def start(self, dark=False):
        self.add_page()
        self.nslide += 1
        if dark:
            self.set_fill_color(20, 16, 14)
            self.rect(0, 0, W, H, "F")
        else:
            self.set_fill_color(250, 250, 249)
            self.rect(0, 0, W, H, "F")
        self.set_fill_color(*R)
        self.rect(0, 0, 4, H, "F")
        if not dark:
            self.set_font("DejaVu", "", 8)
            self.set_text_color(168, 162, 158)
            self.set_xy(10, H - 8)
            self.cell(280, 5, "Ондулин  ·  точки роста  ·  гипотезы к сверке", 0)
            self.cell(40, 5, f"{self.nslide} / {self.total}", 0, align="R")

    def kicker(self, t, dark=False):
        self.set_font("DejaVu", "B", 10)
        self.set_text_color(*R)
        self.set_xy(12, 10)
        self.cell(300, 7, t.upper())

    def h1(self, t, dark=False, size=22):
        self.set_font("DejaVu", "B", size)
        self.set_text_color(255, 255, 255) if dark else self.set_text_color(*INK)
        self.set_xy(12, 20)
        self.multi_cell(310, 10, t)

    def body(self, t, y=42, dark=False, size=12):
        self.set_font("DejaVu", "", size)
        self.set_text_color(214, 211, 209) if dark else self.set_text_color(*MUTED)
        self.set_xy(12, y)
        self.multi_cell(310, 6.2, t)

    def box(self, x, y, w, h, title, text):
        self.set_fill_color(255, 255, 255)
        self.set_draw_color(231, 229, 228)
        self.rect(x, y, w, h, "FD")
        self.set_xy(x + 3, y + 2)
        self.set_font("DejaVu", "B", 11)
        self.set_text_color(*INK)
        self.multi_cell(w - 6, 5.5, title)
        self.set_x(x + 3)
        self.set_font("DejaVu", "", 9.5)
        self.set_text_color(*MUTED)
        self.multi_cell(w - 6, 4.8, text)


